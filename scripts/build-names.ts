// Writes the names entries, @johnmorrisdotca/kuni/names/<language>: src/names/<language>.ts (the entry) and
// src/data/names/<language>.data.ts (its rows), for French, Spanish, German, Simplified and Traditional Chinese, Korean,
// Portuguese, Arabic and Russian, from Unicode CLDR 48.2.0's territories.json in cldr-localenames-full on npm (Unicode-3.0).
// Nothing is downloaded: the input is in node_modules. Running it twice leaves the tree as it was.
//
//   pnpm data:names
//
// A country's name, its short form (alt-short) and its other forms (the rest of its alt- keys) are CLDR's, made NFC with
// full-width letters and digits made ordinary and spaces tidied (the same `tidy` as build-data.ts). A name CLDR does not have
// in the language is null: never copied in from another language, never made up.

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { NAMES_ALIASES } from "./names-config.ts";
import type { NamesLanguage } from "../src/names.ts";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const LANGUAGES: readonly { language: NamesLanguage; label: string }[] = [
  { language: "fr", label: "French" },
  { language: "es", label: "Spanish" },
  { language: "de", label: "German" },
  { language: "zh-Hans", label: "Simplified Chinese" },
  { language: "zh-Hant", label: "Traditional Chinese" },
  { language: "ko", label: "Korean" },
  { language: "pt", label: "Portuguese" },
  { language: "ar", label: "Arabic" },
  { language: "ru", label: "Russian" },
];

const tidy = (text: string): string =>
  text
    .normalize("NFC")
    .replace(/[０-９Ａ-Ｚａ-ｚ]/g, (wide) => String.fromCharCode(wide.charCodeAt(0) - 0xfee0))
    .replace(/[\u3000\s]+/g, " ")
    .trim();

// The 250 codes the package already has, read from its own generated list so the two cannot differ.
const codesSource = readFileSync(join(ROOT, "src/data/codes.data.ts"), "utf8");
const codes = [...codesSource.slice(codesSource.indexOf("COUNTRY_CODES = ["), codesSource.indexOf("] as const")).matchAll(/"([A-Z]{2})"/g)].map((found) => found[1]!);
if (codes.length !== 250) throw new Error(`expected 250 codes, read ${codes.length}`);

// A fold that is only for choosing examples and dropping repeats: exact text is what is compared.
for (const { language, label } of LANGUAGES) {
  const file = join(ROOT, "node_modules/cldr-localenames-full/main", language, "territories.json");
  const territories = (JSON.parse(readFileSync(file, "utf8")) as { main: Record<string, { localeDisplayNames: { territories: Record<string, string> } }> }).main[language]!
    .localeDisplayNames.territories;
  const rows = codes.map((code) => {
    const name = territories[code] === undefined ? null : tidy(territories[code]);
    const short = territories[`${code}-alt-short`] === undefined ? null : tidy(territories[`${code}-alt-short`]!);
    const known = new Set([name, short]);
    const variants: string[] = [];
    for (const [key, value] of Object.entries(territories)) {
      if (!key.startsWith(`${code}-alt-`) || key.endsWith("-alt-short")) continue;
      const variant = tidy(value);
      if (known.has(variant)) continue;
      known.add(variant);
      variants.push(variant);
    }
    const aliases = (NAMES_ALIASES[language]?.[code] ?? []).map(tidy).filter((alias) => !known.has(alias));

    return { code, name, short, variants, aliases };
  });
  for (const row of rows) for (const text of [row.name ?? "", row.short ?? "", ...row.variants, ...row.aliases]) if (/[|]/.test(text)) throw new Error(`${language} ${row.code} has a | in ${text}`);

  const named = rows.filter((row) => row.name !== null).length;
  const lines = rows.map((row) => `    ${row.code}: [${JSON.stringify(row.name)}, ${JSON.stringify(row.short)}, ${JSON.stringify(row.variants.join("|"))}, ${JSON.stringify(row.aliases.join("|"))}],`);
  const constant = language.replace("-", "_").toUpperCase();
  mkdirSync(join(ROOT, "src/data/names"), { recursive: true });
  writeFileSync(
    join(ROOT, "src/data/names", `${language}.data.ts`),
    `// Generated by scripts/build-names.ts. Do not edit by hand: change the script or its inputs and run pnpm data:names.
// The countries' names in ${label}: ${named} of 250 have one, the rest are null.
// Source: Unicode CLDR 48.2.0 (Unicode-3.0), cldr-localenames-full 48.2.0 on npm, ${language}/territories.json; the aliases are hand-written (scripts/names-config.ts).

import type { NamesData } from "../../names";

// code: [name, short name, variants joined by "|", search aliases joined by "|"]; null where CLDR has no name.
const ${constant}: NamesData = {
  language: "${language}",
  countries: {
${lines.join("\n")}
  },
};

export { ${constant} };
`,
  );

  const jp = rows.find((row) => row.code === "JP")!;
  const example = rows.find((row) => row.code === "DE")!;
  const typed = example.name ?? "";
  mkdirSync(join(ROOT, "src/names"), { recursive: true });
  writeFileSync(
    join(ROOT, "src/names", `${language}.ts`),
    `// Generated by scripts/build-names.ts. Do not edit by hand.
// The entry @johnmorrisdotca/kuni/names/${language}: the names of the countries in ${label}, from Unicode CLDR.

import { ${constant} } from "../data/names/${language}.data";
import { createNames } from "../names";
import type { NamedCountry, Names, NamesLanguage, NamesListOptions, NamesNameOptions } from "../names";

/**
 * The countries' names in ${label}: \`countryName\`, \`countryVariants\`, \`countryByName\` (search that folds as ${label} is typed), \`countries\` and \`fold\`. ${named} of the 250 countries have a name in CLDR; the rest answer \`null\`. Also the default export.
 *
 * @example
 * \`\`\`ts
 * import names from "@johnmorrisdotca/kuni/names/${language}";
 *
 * console.log(names.language);                   // ${JSON.stringify(language)}
 * console.log(names.countryName("JP"));          // ${JSON.stringify(jp.name)}
 * console.log(names.countryByName(${JSON.stringify(typed.toUpperCase())}));   // "DE"
 * console.log(names.countries().length);         // 250
 * \`\`\`
 */
const names: Names = createNames(${constant});

export default names;
export { names };
export type { NamedCountry, Names, NamesLanguage, NamesListOptions, NamesNameOptions };
`,
  );
  console.log(`${language}: ${named} names, ${250 - named} null, ${rows.filter((row) => row.short !== null).length} short, ${rows.filter((row) => row.variants.length > 0).length} with variants`);
}
